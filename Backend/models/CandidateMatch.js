const mongoose = require("mongoose");

const candidateMatchSchema = new mongoose.Schema(
  {
    // Which BGV run this match belongs to
    bgvRun: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "BgvRun",
      required: true,
    },

    // Candidate being verified
    candidate: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Candidate",
      required: true,
    },

    // External search result being compared
    searchResult: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "SearchResult",
      required: true,
    },

    // Overall similarity score
    similarityScore: {
      type: Number,
      min: 0,
      max: 100,
      default: 0,
    },

    // Operational matching status
    matchStatus: {
      type: String,
      enum: [
        "STRONG",
        "POSSIBLE",
        "WEAK",
        "CONFLICT",
        "REVIEW_REQUIRED",
      ],
      default: "REVIEW_REQUIRED",
    },

    // Fields that matched
    matchedSignals: {
      name: {
        matched: {
          type: Boolean,
          default: false,
        },
        score: {
          type: Number,
          default: 0,
        },
      },

      company: {
        matched: {
          type: Boolean,
          default: false,
        },
        score: {
          type: Number,
          default: 0,
        },
      },

      jobTitle: {
        matched: {
          type: Boolean,
          default: false,
        },
        score: {
          type: Number,
          default: 0,
        },
      },

      location: {
        matched: {
          type: Boolean,
          default: false,
        },
        score: {
          type: Number,
          default: 0,
        },
      },

      education: {
        matched: {
          type: Boolean,
          default: false,
        },
        score: {
          type: Number,
          default: 0,
        },
      },

      profileUrl: {
        matched: {
          type: Boolean,
          default: false,
        },
        score: {
          type: Number,
          default: 0,
        },
      },

      username: {
        matched: {
          type: Boolean,
          default: false,
        },
        score: {
          type: Number,
          default: 0,
        },
      },
    },

    // Fields that conflict
    conflictingSignals: [
      {
        field: {
          type: String,
          trim: true,
        },

        candidateValue: {
          type: String,
          trim: true,
        },

        searchResultValue: {
          type: String,
          trim: true,
        },

        reason: {
          type: String,
          trim: true,
        },
        severity: {
          type: String,
          enum: ["SOFT", "HARD"],
        },
      },
    ],

    // Structured, inspectable breakdown (identity / components / relevance /
    // data quality). Identity confidence is kept separate from relevance.
    matchDetails: {
      type: mongoose.Schema.Types.Mixed,
    },

    // Explanation generated by matching system
    explanation: {
      type: String,
      trim: true,
    },

    // Human review
    reviewStatus: {
      type: String,
      enum: ["PENDING", "APPROVED", "REJECTED"],
      default: "PENDING",
    },

    // User who performed the review
    reviewedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
    },

    // Time when review was performed
    reviewedAt: {
      type: Date,
    },

    // Optional notes from reviewer
    reviewerNotes: {
      type: String,
      trim: true,
    },
  },
  {
    timestamps: true,
  }
);

// One match per (run, search result): matching can be re-run safely.
candidateMatchSchema.index(
  { bgvRun: 1, searchResult: 1 },
  { unique: true }
);
candidateMatchSchema.index({ bgvRun: 1, reviewStatus: 1 });

const CandidateMatch = mongoose.model(
  "CandidateMatch",
  candidateMatchSchema
);

module.exports = CandidateMatch;